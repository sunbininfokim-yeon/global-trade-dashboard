export function resolveNoticeReview(notice, caseId, reviews = AD_NOTICE_REVIEWS) {
  const review = reviews.find(r => r.case_id === caseId && r.document_id === notice.document_id);
  if (!review || notice.case_id !== caseId) return null;
  // A changed/corrected or disappeared source must be re-reviewed even when retained bytes match.
  if (!['needs_review', 'catalogued_not_reconciled'].includes(notice.review_status) ||
      !notice.content_hash || !notice.metadata_hash ||
      review.content_hash !== notice.content_hash || review.metadata_hash !== notice.metadata_hash ||
      review.published !== notice.published) return null;
  return structuredClone(review);
}
