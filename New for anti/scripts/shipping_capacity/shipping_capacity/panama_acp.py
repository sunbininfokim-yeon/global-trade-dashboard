def aggregate_daily_gatun_to_monthly(
    levels: list[DailyGatunLevel],
    monthly_covariates: list[dict[str, str]],
) -> list[MonthlyHydrologyRecord]:
    """Join observed ACP levels to local monthly climate/operations covariates.

    Monthly covariates must be independently prepared from their licensed
    sources.  At least 20 observed daily levels are required for any month;
    sparse months are rejected rather than silently filled or interpolated.
    """

    by_month: dict[str, list[float]] = {}
    for row in levels:
        by_month.setdefault(row.observation_date[:7], []).append(row.water_level_ft)
    covariates = {str(row.get("month", "")): row for row in monthly_covariates}
    if not covariates:
        raise ACPModelError("monthly covariates are required")
    if len(covariates) != len(monthly_covariates):
        raise ACPModelError("monthly covariates contain duplicate months")

    def optional(row: dict[str, str], name: str) -> float | None:
        value = row.get(name)
        return None if value in (None, "") else float(value)

    merged: list[MonthlyHydrologyRecord] = []
    for month in sorted(covariates):
        try:
            datetime.strptime(month, "%Y-%m")
        except ValueError as exc:
            raise ACPModelError(f"invalid covariate month: {month}") from exc
        observed = by_month.get(month, [])
        if len(observed) < 20:
            raise ACPModelError(f"ACP level coverage below 20 daily observations for {month}")
        row = covariates[month]
        try:
            merged.append(MonthlyHydrologyRecord(
                month=month,
                gatun_mean_ft=statistics.fmean(observed),
                precipitation_mm=float(str(row["precipitation_mm"])),
                evaporation_mm=float(str(row["evaporation_mm"])),
                oceangoing_transits_daily_average=optional(row, "oceangoing_transits_daily_average"),
                booking_slots_per_day=optional(row, "booking_slots_per_day"),
                neopanamax_max_draft_ft=optional(row, "neopanamax_max_draft_ft"),
                panamax_max_draft_ft=optional(row, "panamax_max_draft_ft"),
                oni_lag_6w=optional(row, "oni_lag_6w"),
            ))
        except (KeyError, TypeError, ValueError) as exc:
            raise ACPModelError(f"invalid covariates for {month}") from exc
    return merged


def hydrology_design(records: list[MonthlyHydrologyRecord]) -> tuple[list[list[float]], list[float], list[str]]:
    """Build the paper-aligned monthly GAM design without filling missing months."""

    if any(
        datetime.strptime(records[index + 1].month, "%Y-%m").year * 12
        + datetime.strptime(records[index + 1].month, "%Y-%m").month
        != datetime.strptime(records[index].month, "%Y-%m").year * 12
        + datetime.strptime(records[index].month, "%Y-%m").month + 1
        for index in range(len(records) - 1)
    ):
        raise ACPModelError("history must be consecutive monthly observations; no imputation is allowed")
    features: list[list[float]] = []
    target: list[float] = []
    months: list[str] = []
    for index in range(11, len(records)):
        row = records[index]
        trailing = records[index - 11 : index + 1]
        features.append(
            [
                row.precipitation_mm,
                row.evaporation_mm,
                sum(item.precipitation_mm for item in trailing),
                sum(item.evaporation_mm for item in trailing),
            ]
        )
        target.append(row.gatun_mean_ft)
        months.append(row.month)
    return features, target, months


def _seasonal_baseline(train_target: list[float], train_months: list[str], test_months: list[str]) -> list[float]:
    by_month: dict[int, list[float]] = {}
    for value, stamp in zip(train_target, train_months):
        by_month.setdefault(datetime.strptime(stamp, "%Y-%m").month, []).append(value)
    fallback = statistics.fmean(train_target)
    return [
        statistics.fmean(by_month.get(datetime.strptime(stamp, "%Y-%m").month, [fallback]))
        for stamp in test_months
    ]


def fit_hydrology_gam(records: list[MonthlyHydrologyRecord]) -> dict[str, Any]:
    """Fit the paper-aligned additive hydrology model with an annual holdout.

    `mgcv::gam` with REML is the reference implementation published by Muñoz
    et al.  The deployable project deliberately avoids an R runtime, so this
    is an explicit Python additive-spline approximation.  It retains the four
    published covariates, 20 spline bases per term, 3x tail weighting, and a
    final 12-month chronological validation; it does not claim numerical
    identity with the authors' mgcv fit.
    """

    paper_features, paper_target, paper_months = hydrology_design(records)
    if len(paper_target) < MIN_HYDROLOGY_MONTHS:
        return {
            "status": "insufficient_authorized_history",
            "forecast_use": "withheld",
            "sample_count": len(paper_target),
            "minimum_sample_count": MIN_HYDROLOGY_MONTHS,
            "required_columns": ["gatun_mean_ft", "precipitation_mm", "evaporation_mm"],
        }
    try:
        import numpy as np
        from sklearn.linear_model import Ridge
        from sklearn.pipeline import make_pipeline
        from sklearn.preprocessing import SplineTransformer, StandardScaler
    except ImportError as exc:
        return {
            "status": "dependency_missing",
            "forecast_use": "withheld",
            "missing_dependency": str(exc),
        }
    aligned = [
        (features, target, month, row.oni_lag_6w)
        for features, target, month, row in zip(paper_features, paper_target, paper_months, records[11:])
        if row.oni_lag_6w is not None
    ]
    if len(aligned) >= MIN_HYDROLOGY_MONTHS:
        paper_features = [row[0] for row in aligned]
        paper_target = [row[1] for row in aligned]
        paper_months = [row[2] for row in aligned]

    def backtest(name: str, features: list[list[float]], target: list[float], months: list[str]) -> dict[str, Any]:
        split = len(target) - 12
        x_train, x_test = np.asarray(features[:split]), np.asarray(features[split:])
        y_train, y_test = np.asarray(target[:split]), np.asarray(target[split:])
        low_threshold, high_threshold = np.quantile(y_train, [0.1, 0.9])
        sample_weight = np.where((y_train < low_threshold) | (y_train > high_threshold), 3.0, 1.0)
        model = make_pipeline(
            SplineTransformer(n_knots=20, degree=3, extrapolation="linear"),
            StandardScaler(),
            Ridge(alpha=2.0),
        )
        model.fit(x_train, y_train, ridge__sample_weight=sample_weight)
        predicted = model.predict(x_test)
        baseline = _seasonal_baseline(target[:split], months[:split], months[split:])
        model_mae = float(np.mean(np.abs(y_test - predicted)))
        baseline_mae = statistics.fmean(abs(actual - expected) for actual, expected in zip(y_test, baseline))
        improvement = None if baseline_mae == 0 else 1 - model_mae / baseline_mae
        residual_sigma = float(np.sqrt(np.mean((y_test - predicted) ** 2)))
        return {
            "candidate_id": name,
            "sample_count": len(target),
            "train_count": len(y_train),
            "test_count": len(y_test),
            "holdout_start_month": months[split],
            "model_mae_ft": round(model_mae, 4),
            "seasonal_baseline_mae_ft": round(baseline_mae, 4),
            "holdout_rmse_ft": round(residual_sigma, 4),
            "approximate_95pct_prediction_half_width_ft": round(1.96 * residual_sigma, 4),
            "improvement_vs_seasonal_baseline": round(improvement, 4) if improvement is not None else None,
        }

    candidates = [backtest("paper_gam", paper_features, paper_target, paper_months)]
    if len(aligned) >= MIN_HYDROLOGY_MONTHS:
        enso_features = [row[0] + [float(row[3])] for row in aligned]
        candidates.append(backtest("paper_gam_plus_lagged_oni", enso_features, paper_target, paper_months))
    selected = min(candidates, key=lambda item: item["model_mae_ft"])
    improvement = selected["improvement_vs_seasonal_baseline"]
    return {
        "status": "backtested",
        "method": "candidate-selected monthly additive spline GAM: paper four-term specification versus optional lagged-ONI challenger; same final 12-month chronological holdout",
        "research_basis": MUÑOZ_2025_DOI,
        "selected_candidate": selected["candidate_id"],
        **{key: value for key, value in selected.items() if key != "candidate_id"},
        "candidate_backtests": candidates,
        "forecast_use": "research_only" if improvement is not None and improvement >= 0.05 else "withheld",
        "publication_gate": "selected candidate requires at least 5% holdout MAE improvement versus seasonal baseline; lagged ONI is retained only if it improves the identical holdout; no model may override ACP Advisories",
    }


def forecast_hydrology_ensemble(
    records: list[MonthlyHydrologyRecord], members: list[MonthlyClimateForecastMember]
) -> dict[str, Any]:
    """Project the next monthly Gatun level from an external climate ensemble."""

    backtest = fit_hydrology_gam(records)
    if backtest.get("forecast_use") != "research_only":
        return {"status": "withheld_failed_hydrology_backtest", "forecast_use": "withheld"}
    target_months = sorted({member.month for member in members})
    if len(target_months) != 1:
        return {"status": "one_target_month_required", "forecast_use": "withheld", "months": target_months}
    latest = datetime.strptime(records[-1].month, "%Y-%m")
    serial = latest.year * 12 + latest.month
    expected = f"{serial // 12:04d}-{serial % 12 + 1:02d}"
    if target_months[0] != expected:
        return {
            "status": "forecast_must_be_next_consecutive_month",
            "forecast_use": "withheld",
            "latest_history_month": records[-1].month,
            "target_month": target_months[0],
        }
    try:
        import numpy as np
        from sklearn.linear_model import Ridge
        from sklearn.pipeline import make_pipeline
        from sklearn.preprocessing import SplineTransformer, StandardScaler
    except ImportError as exc:
        return {"status": "dependency_missing", "forecast_use": "withheld", "missing_dependency": str(exc)}
    paper_features, target, months = hydrology_design(records)
    selected = backtest["selected_candidate"]
    if selected == "paper_gam_plus_lagged_oni":
        aligned = [
            (features + [float(row.oni_lag_6w)], value, month)
            for features, value, month, row in zip(paper_features, target, months, records[11:])
            if row.oni_lag_6w is not None
        ]
        paper_features = [row[0] for row in aligned]
        target = [row[1] for row in aligned]
        if any(member.oni is None for member in members):
            return {"status": "selected_enso_model_requires_forecast_oni", "forecast_use": "withheld"}
    train_x = np.asarray(paper_features)
    train_y = np.asarray(target)
    low, high = np.quantile(train_y, [0.1, 0.9])
    weights = np.where((train_y < low) | (train_y > high), 3.0, 1.0)
    model = make_pipeline(
        SplineTransformer(n_knots=20, degree=3, extrapolation="linear"), StandardScaler(), Ridge(alpha=2.0)
    )
    model.fit(train_x, train_y, ridge__sample_weight=weights)
    trailing = records[-11:]
    forecast_features = []
    for member in members:
        features = [
            member.precipitation_mm,
            member.evaporation_mm,
            sum(row.precipitation_mm for row in trailing) + member.precipitation_mm,
            sum(row.evaporation_mm for row in trailing) + member.evaporation_mm,
        ]
        if selected == "paper_gam_plus_lagged_oni":
            features.append(float(member.oni))
        forecast_features.append(features)
    predictions = model.predict(np.asarray(forecast_features))
    by_source = {}
    for source_id in sorted({member.source_id for member in members}):
        values = [
            float(prediction) for member, prediction in zip(members, predictions) if member.source_id == source_id
        ]
        by_source[source_id] = {
            "member_count": len(values),
            "p10_water_level_ft": round(float(np.quantile(values, 0.1)), 3),
            "median_water_level_ft": round(float(np.quantile(values, 0.5)), 3),
            "p90_water_level_ft": round(float(np.quantile(values, 0.9)), 3),
        }
    half_width = float(backtest["approximate_95pct_prediction_half_width_ft"])
    pooled = [float(value) for value in predictions]
    return {
        "status": "research_only_external_ensemble_forecast",
        "forecast_use": "research_only",
        "target_month": target_months[0],
        "selected_hydrology_candidate": selected,
        "sources": by_source,
        "pooled_member_count": len(pooled),
        "pooled_median_water_level_ft": round(float(np.quantile(pooled, 0.5)), 3),
        "conservative_95pct_range_ft": [
            round(float(np.quantile(pooled, 0.1)) - half_width, 3),
            round(float(np.quantile(pooled, 0.9)) + half_width, 3),
        ],
        "warning": "multi-source pooling weights individual members; compare source-level ranges before use",
    }


def fit_transit_response(
    hydrology: list[MonthlyHydrologyRecord],
    operations: list[MonthlyCanalOperations],
    published_projection: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Backtest a leakage-controlled monthly ACP transit response model.

    Current-month water level and *available* booking slots may be known from
    ACP forecasts/notices. Demand and congestion variables use the preceding
    month only. Current-month used slots, arrivals and waiting time are never
    predictors because they would not exist at forecast issue time.
    """

    hydro_by_month = {row.month: row for row in hydrology}
    ordered = sorted(operations, key=lambda item: item.month)
    x: list[list[float]] = []
    y: list[float] = []
    months: list[str] = []
    persistence: list[float] = []
    for previous, current in zip(ordered, ordered[1:]):
        prev_stamp = datetime.strptime(previous.month, "%Y-%m")
        curr_stamp = datetime.strptime(current.month, "%Y-%m")
        if curr_stamp.year * 12 + curr_stamp.month != prev_stamp.year * 12 + prev_stamp.month + 1:
            continue
        hydro = hydro_by_month.get(current.month)
        previous_hydro = hydro_by_month.get(previous.month)
        if (
            hydro is None or previous_hydro is None
            or current.booking_available_total is None or previous.booking_available_total is None
        ):
            continue
        days = calendar.monthrange(curr_stamp.year, curr_stamp.month)[1]
        previous_days = calendar.monthrange(prev_stamp.year, prev_stamp.month)[1]
        month_number = curr_stamp.month
        x.append([
            hydro.gatun_mean_ft - previous_hydro.gatun_mean_ft,
            current.booking_available_total / days - previous.booking_available_total / previous_days,
            previous.arrivals_daily_average - previous.oceangoing_transits_daily_average,
            (previous.booking_utilization_pct if previous.booking_utilization_pct is not None else 100.0) - 100.0,
            previous.canal_waters_time_hours,
            hydro.gatun_mean_ft,
            math.sin(2 * math.pi * month_number / 12),
            math.cos(2 * math.pi * month_number / 12),
        ])
        y.append(current.oceangoing_transits_daily_average)
        months.append(current.month)
        persistence.append(previous.oceangoing_transits_daily_average)
    if len(y) < MIN_TRANSIT_MONTHS:
        return {
            "status": "insufficient_authorized_operations_history",
            "forecast_use": "withheld",
            "sample_count": len(y),
            "minimum_sample_count": MIN_TRANSIT_MONTHS,
            "required_columns": [
                "monthly Gatun mean",
                "official monthly available booking slots",
                "lagged official transits/arrivals/booking utilization/canal waters time",
            ],
        }
    try:
        import numpy as np
        from sklearn.linear_model import Ridge
        from sklearn.linear_model import HuberRegressor
        from sklearn.pipeline import make_pipeline
        from sklearn.ensemble import RandomForestRegressor
        from sklearn.preprocessing import StandardScaler
    except ImportError as exc:
        return {"status": "dependency_missing", "forecast_use": "withheld", "missing_dependency": str(exc)}
    split = len(y) - 12
    train_x, test_x = np.asarray(x[:split]), np.asarray(x[split:])
    train_y, test_y = np.asarray(y[:split]), np.asarray(y[split:])
    delta_y = np.asarray([actual - prior for actual, prior in zip(y, persistence)])
    train_delta = delta_y[:split]
    candidates = {
        "ridge": make_pipeline(StandardScaler(), Ridge(alpha=2.0)),
        "huber": make_pipeline(StandardScaler(), HuberRegressor(epsilon=1.5, alpha=0.5, max_iter=1000)),
        "random_forest": RandomForestRegressor(
            n_estimators=400, min_samples_leaf=3, max_features=0.75, random_state=42
        ),
    }
    candidate_metrics = []
    for candidate_id, model in candidates.items():
        model.fit(train_x, train_delta)
        predicted = np.asarray(persistence[split:]) + model.predict(test_x)
        residuals = [abs(float(actual - estimate)) for actual, estimate in zip(test_y, predicted)]
        candidate_metrics.append({
            "candidate_id": candidate_id,
            "mae_transits_per_day": round(statistics.fmean(residuals), 4),
            "rmse_transits_per_day": round(float(np.sqrt(np.mean((test_y - predicted) ** 2))), 4),
            "empirical_p90_absolute_error": round(float(np.quantile(residuals, 0.9)), 4),
        })
    selected = min(candidate_metrics, key=lambda item: item["mae_transits_per_day"])
    seasonal = _seasonal_baseline(y[:split], months[:split], months[split:])
    seasonal_mae = statistics.fmean(abs(actual - estimate) for actual, estimate in zip(y[split:], seasonal))
    persistence_mae = statistics.fmean(
        abs(actual - estimate) for actual, estimate in zip(y[split:], persistence[split:])
    )
    baseline_mae = min(seasonal_mae, persistence_mae)
    model_mae = selected["mae_transits_per_day"]
    improvement = None if baseline_mae == 0 else 1 - model_mae / baseline_mae
    forecast_use = "research_only" if improvement is not None and improvement >= 0.05 else "withheld"
    forecast = None
    if forecast_use == "research_only" and published_projection:
        target_month = str(published_projection.get("month", ""))
        latest = ordered[-1]
        target_stamp = datetime.strptime(target_month, "%Y-%m")
        latest_stamp = datetime.strptime(latest.month, "%Y-%m")
        gap = target_stamp.year * 12 + target_stamp.month - (latest_stamp.year * 12 + latest_stamp.month)
        if 1 <= gap <= 2 and latest.booking_available_total is not None:
            selected_model = candidates[selected["candidate_id"]]
            selected_model.fit(np.asarray(x), delta_y)
            state_transits = latest.oceangoing_transits_daily_average
            queue_pressure = latest.arrivals_daily_average - latest.oceangoing_transits_daily_average
            state_water = hydro_by_month[latest.month].gatun_mean_ft
            latest_days = calendar.monthrange(latest_stamp.year, latest_stamp.month)[1]
            slots_per_day = latest.booking_available_total / latest_days
            path = []
            for step in range(1, gap + 1):
                serial = latest_stamp.year * 12 + latest_stamp.month - 1 + step
                month = f"{serial // 12:04d}-{serial % 12 + 1:02d}"
                stamp = datetime.strptime(month, "%Y-%m")
                if month == target_month:
                    water = float(published_projection["mean_water_level_ft"])
                elif month in hydro_by_month:
                    water = hydro_by_month[month].gatun_mean_ft
                else:
                    break
                features = np.asarray([[
                    water - state_water,
                    0.0,
                    queue_pressure,
                    (latest.booking_utilization_pct if latest.booking_utilization_pct is not None else 100.0) - 100.0,
                    latest.canal_waters_time_hours,
                    water,
                    math.sin(2 * math.pi * stamp.month / 12),
                    math.cos(2 * math.pi * stamp.month / 12),
                ]])
                state_transits += float(selected_model.predict(features)[0])
                state_water = water
                path.append({"month": month, "point_transits_per_day": round(state_transits, 3)})
            if len(path) == gap:
                p90 = float(selected["empirical_p90_absolute_error"]) * math.sqrt(gap)
                forecast = {
                    "status": "research_scenario_with_carried_forward_operations",
                    "target_month": target_month,
                    "point_transits_per_day": path[-1]["point_transits_per_day"],
                    "empirical_p90_range_transits_per_day": [
                        round(max(0.0, path[-1]["point_transits_per_day"] - p90), 3),
                        round(path[-1]["point_transits_per_day"] + p90, 3),
                    ],
                    "recursive_path": path,
                    "assumptions": [
                        f"latest official monthly operations label is {latest.month}",
                        f"available booking slots per day carried forward at {slots_per_day:.3f}",
                        "latest official queue pressure, booking utilization and Canal Waters Time carried forward",
                        "target water level uses ACP's published projection; intermediate current month uses observed partial-month mean when available",
                    ],
                    "not_for_publication": True,
                }
    return {
        "status": "backtested",
        "method": "leakage-controlled monthly-change response: ridge, robust Huber and conservative random forest predict change from persistence using Gatun/available-slot changes plus lagged queue pressure and congestion; final 12-month holdout",
        "sample_count": len(y),
        "train_count": split,
        "test_count": len(y) - split,
        "holdout_start_month": months[split],
        "selected_candidate": selected["candidate_id"],
        "candidate_backtests": candidate_metrics,
        "model_mae_transits_per_day": model_mae,
        "seasonal_baseline_mae_transits_per_day": round(seasonal_mae, 4),
        "persistence_baseline_mae_transits_per_day": round(persistence_mae, 4),
        "best_baseline_mae_transits_per_day": round(baseline_mae, 4),
        "improvement_vs_best_baseline": round(improvement, 4) if improvement is not None else None,
        "forecast_use": forecast_use,
        "forecast": forecast,
        "publication_gate": "requires at least 5% holdout MAE improvement versus the better of seasonal and persistence baselines; no current-month demand leakage",
    }


