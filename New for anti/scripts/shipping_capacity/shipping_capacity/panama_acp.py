def extract_pdf_text(pdf_bytes: bytes) -> str:
    """Extract text locally; pypdf remains an optional runtime dependency."""

    try:
        from pypdf import PdfReader
    except ImportError as exc:  # pragma: no cover - depends on local extras
        raise ACPModelError("pypdf is required to parse an ACP PDF") from exc
    reader = PdfReader(io.BytesIO(pdf_bytes))
    if reader.is_encrypted:
        try:
            reader.decrypt("")
        except Exception as exc:
            raise ACPModelError("encrypted ACP PDF cannot be opened with an empty password") from exc
    return "\n".join(page.extract_text() or "" for page in reader.pages)


def _parse_acp_date(value: str) -> str:
    normalized = value.replace(".", "").strip()
    for pattern in ("%b %d, %Y", "%B %d, %Y"):
        try:
            return datetime.strptime(normalized, pattern).date().isoformat()
        except ValueError:
            pass
    raise ACPModelError(f"unrecognized ACP date: {value!r}")


def _first_float(patterns: Iterable[str], text: str, label: str) -> float | None:
    for pattern in patterns:
        match = re.search(pattern, text, flags=re.IGNORECASE | re.DOTALL)
        if match:
            return float(match.group(1))
    return None


def parse_gatun_dashboard_text(text: str, *, source_url: str = ACP_GATUN_DASHBOARD_PDF) -> GatunDashboardSnapshot:
    """Parse only explicitly labelled values from ACP's public dashboard PDF."""

    compact = re.sub(r"\s+", " ", text)
    date_match = re.search(
        r"Official Gatun Water Level\s+for\s+([A-Za-z]{3,9}\.?\s+\d{1,2},\s+\d{4})",
        compact,
        flags=re.IGNORECASE,
    )
    if not date_match:
        raise ACPModelError("official Gatun observation date not found")
    observation_date = _parse_acp_date(date_match.group(1))
    date_start = max(0, date_match.start() - 40)
    date_end = min(len(compact), date_match.end() + 80)
    local = compact[date_start:date_end]
    water_level_ft = _first_float(
        (r"([0-9]+(?:\.[0-9]+)?)\s*ft\s+Official Gatun Water Level",),
        local,
        "water level",
    )
    if water_level_ft is None:
        water_level_ft = _first_float(
            (r"Official Gatun Water Level.*?([0-9]+(?:\.[0-9]+)?)\s*ft",),
            local,
            "water level",
        )
    if water_level_ft is None:
        raise ACPModelError("official Gatun water level not found")

    surcharge = _first_float(
        (
            r"([0-9]+(?:\.[0-9]+)?)%\s+Variable Fresh Water Surcharge",
            r"Variable Fresh Water Surcharge.*?([0-9]+(?:\.[0-9]+)?)%",
        ),
        compact,
        "fresh water surcharge",
    )
    drafts = re.search(
        r"Official Maximum Draft\s+Neopanamax\s+Panamax\s+"
        r"([0-9]+(?:\.[0-9]+)?)\s*ft\s*([0-9]+(?:\.[0-9]+)?)\s*ft",
        compact,
        flags=re.IGNORECASE,
    )
    if not drafts:
        # ACP's visual layout can put the values above the title in the PDF
        # text stream even though the screen displays the title above them.
        drafts = re.search(
            r"Neopanamax\s+Panamax\s+([0-9]+(?:\.[0-9]+)?)\s*ft\s*"
            r"([0-9]+(?:\.[0-9]+)?)\s*ft\s+Official Maximum Draft",
            compact,
            flags=re.IGNORECASE,
        )
    projection = re.search(
        r"Last projection uploaded on:\s*([^\n]+?)(?:\s+Probable|\s+The estimated)",
        text,
        flags=re.IGNORECASE | re.DOTALL,
    )
    return GatunDashboardSnapshot(
        observation_date=observation_date,
        water_level_ft=water_level_ft,
        fresh_water_surcharge_pct=surcharge,
        neopanamax_max_draft_ft=float(drafts.group(1)) if drafts else None,
        panamax_max_draft_ft=float(drafts.group(2)) if drafts else None,
        projection_uploaded_at=re.sub(r"\s+", " ", projection.group(1)).strip() if projection else None,
        source_url=source_url,
    )


