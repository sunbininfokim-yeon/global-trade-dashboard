def parse_booking_slot_windows(text: str, *, source_url: str) -> list[BookingSlotWindow]:
    """Extract explicit booking-slot dates from an ACP Advisory.

    The parser intentionally accepts only sentences with a concrete start date
    and slots-per-day value.  It never interprets a chart or extrapolates an
    "until further notice" period into a synthetic end date.
    """

    compact = re.sub(r"\s+", " ", text)
    advisory_match = re.search(r"Advisory To Shipping No\.\s*([A-Z]-\d+-\d{4})", compact, re.I)
    advisory_id = advisory_match.group(1) if advisory_match else None
    month = r"(?:January|February|March|April|May|June|July|August|September|October|November|December)"
    partial_stamp = rf"(?P<month>{month})\s+(?P<day>\d{{1,2}})(?:,\s*(?P<year>\d{{4}}))?"
    end_stamp = rf"(?P<end_month>{month})\s+(?P<end_day>\d{{1,2}})(?:,\s*(?P<end_year>\d{{4}}))?"
    pattern = re.compile(
        rf"(?:from|For booking dates from|For booking dates beginning)\s+{partial_stamp}"
        rf"(?:\s*,?\s*to\s+{end_stamp}|\s*,?\s*and\s+until\s+further\s+notice)?"
        rf"[^.]*?(?:booking slots?\s+(?:will\s+(?:further\s+)?be\s+)?(?:reduced|increased)\s+to|"
        rf"number of booking slots?\s+(?:will\s+(?:further\s+)?be\s+)?(?:reduced|increased)\s+to)\s+(?P<slots>\d+)",
        re.IGNORECASE,
    )

    def resolve_date(match: re.Match[str], prefix: str, fallback_year: str | None) -> str:
        resolved_year = match.group(f"{prefix}year") or fallback_year
        if resolved_year is None:
            raise ACPModelError("ACP advisory omits a year needed to locate a booking-slot window")
        return _parse_acp_date(
            f"{match.group(f'{prefix}month')} {match.group(f'{prefix}day')}, {resolved_year}"
        )

    windows = []
    for match in pattern.finditer(compact):
        fallback_year = match.group("end_year") or match.group("year")
        windows.append(
            BookingSlotWindow(
                start_date=resolve_date(match, "", fallback_year),
                end_date=(resolve_date(match, "end_", fallback_year) if match.group("end_month") else None),
                slots_per_day=int(match.group("slots")),
                source_url=source_url,
                advisory_id=advisory_id,
            )
        )
    return windows


def discover_operations_summary_urls(index_html: str, *, base_url: str = ACP_ADVISORY_INDEX) -> list[str]:
    """Find official monthly operations PDFs without relying on advisory IDs."""

    candidates = re.findall(r'href=["\']([^"\']+\.pdf(?:\?[^"\']*)?)["\']', index_html, re.I)
    urls = []
    for raw in candidates:
        url = html.unescape(urljoin(base_url, raw))
        normalized = re.sub(r"[-_–—]+", " ", url).lower()
        if "operations summary" in normalized and ("monthly" in normalized or "montly" in normalized):
            urls.append(url)
    return sorted(set(urls))


def parse_monthly_operations_summary(text: str, *, source_url: str) -> MonthlyCanalOperations:
    """Parse only explicitly labelled statistics from an ACP monthly Advisory."""

    compact = re.sub(r"\s+", " ", text.replace("’", "'").replace("–", "-").replace("—", "-"))
    subject = re.search(
        r"(?:Monthly\s+)?Canal Operations Summary\s*-?\s*([A-Za-z]+)\s+(20\d{2})",
        compact,
        re.I,
    )
    if not subject:
        raise ACPModelError("monthly operations subject month not found")
    month_name, year = subject.group(1), subject.group(2)
    try:
        month = datetime.strptime(f"{month_name} {year}", "%B %Y").strftime("%Y-%m")
    except ValueError as exc:
        # One official filename/text uses the typo "Juny".
        if month_name.lower() == "juny":
            month = f"{year}-06"
        else:
            raise ACPModelError(f"unrecognized operations month: {month_name} {year}") from exc

    traffic_section = re.search(r"Traffic Statistics:(.*?)Oceangoing Transits:\s+Total", compact, re.I)
    if not traffic_section:
        raise ACPModelError(f"traffic statistics table not found for {month}")
    table = traffic_section.group(1)
    arrivals = re.search(r"Arrivals\s+([0-9.]+)\s+([0-9.]+)\s+([0-9.]+)", table, re.I)
    traffic = re.search(r"Oceangoing Transits\s+([0-9.]+)\s+([0-9.]+)\s+([0-9.]+)", table, re.I)
    water_time = re.search(r"Canal Waters Time \(hours\)\s+([0-9.]+)", table, re.I)
    transit_time = re.search(r"In-Transit Time \(hours\)\s+([0-9.]+)", table, re.I)
    if not all((arrivals, traffic, water_time, transit_time)):
        raise ACPModelError(f"one or more traffic rows not found for {month}")

    neo = re.search(
        r"Neopanamax Vessels \(107' beam and over\)\s+[0-9,]+\s+([0-9.]+)\s+[0-9.]+",
        compact,
        re.I,
    )
    booking_section = re.search(
        r"Booking Slots:\s+(.*?)(?:\* Does not include|\s+3\.\s+The following)", compact, re.I
    )
    available_values: list[float] = []
    used_values: list[float] = []
    if booking_section:
        for label in ("Neopanamax(?: Vessels)?", "(?:Supers|Large Vessels)", "Regular Vessels"):
            row = re.search(
                rf"{label}.*?\)\s+(?:Available\s+)?([0-9,]+)\*?\s+"
                rf"(?:Used\s+)?([0-9,]+)\*?(?:1|¹)?\s+(?:Percentage\s+)?([0-9.]+)",
                booking_section.group(1),
                re.I,
            )
            if row:
                available_values.append(float(row.group(1).replace(",", "")))
                used_values.append(float(row.group(2).replace(",", "")))
    available_total = sum(available_values) if len(available_values) == 3 else None
    used_total = sum(used_values) if len(used_values) == 3 else None
    utilization = None if not available_total else 100 * used_total / available_total
    advisory_match = re.search(r"Advisory To Shipping No\.\s*([A-Z]-?\d+-\d{4})", compact, re.I)
    return MonthlyCanalOperations(
        month=month,
        arrivals_daily_average=float(arrivals.group(1)),
        oceangoing_transits_daily_average=float(traffic.group(1)),
        oceangoing_transits_high=float(traffic.group(2)),
        oceangoing_transits_low=float(traffic.group(3)),
        canal_waters_time_hours=float(water_time.group(1)),
        in_transit_time_hours=float(transit_time.group(1)),
        neopanamax_transits_daily_average=float(neo.group(1)) if neo else None,
        booking_available_total=available_total,
        booking_used_total=used_total,
        booking_utilization_pct=utilization,
        source_url=source_url,
        advisory_id=advisory_match.group(1) if advisory_match else None,
    )


def fetch_monthly_operations_summaries(
    index_url: str = ACP_ADVISORY_INDEX, *, max_workers: int = 4
) -> tuple[list[MonthlyCanalOperations], list[dict[str, str]]]:
    """Fetch official PDFs in memory and return transparent parse failures."""

    urls = discover_operations_summary_urls(fetch_public_text(index_url), base_url=index_url)
    records: list[MonthlyCanalOperations] = []
    failures: list[dict[str, str]] = []

    def fetch_one(url: str) -> MonthlyCanalOperations:
        return parse_monthly_operations_summary(extract_pdf_text(fetch_public_pdf(url)), source_url=url)

    with ThreadPoolExecutor(max_workers=max(1, min(max_workers, 4))) as pool:
        futures = {pool.submit(fetch_one, url): url for url in urls}
        for future in as_completed(futures):
            url = futures[future]
            try:
                records.append(future.result())
            except Exception as exc:  # keep the entire batch auditable
                failures.append({"source_url": url, "error": str(exc)})
    by_month: dict[str, MonthlyCanalOperations] = {}
    for row in sorted(records, key=lambda item: (item.month, item.source_url)):
        by_month.setdefault(row.month, row)
    return list(by_month.values()), sorted(failures, key=lambda item: item["source_url"])


def load_monthly_history(path: Path) -> list[MonthlyHydrologyRecord]:
    """Load a user-authorized local history; no ACP raw data is committed."""

    required = {"month", "gatun_mean_ft", "precipitation_mm", "evaporation_mm"}
    with path.open(encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle))
    if not rows or not required.issubset(rows[0]):
        raise ACPModelError(f"history CSV needs columns: {sorted(required)}")
    parsed = []
    for row in rows:
        month = str(row["month"])
        try:
            datetime.strptime(month, "%Y-%m")
        except ValueError as exc:
            raise ACPModelError(f"invalid history month: {month}") from exc
        def optional(name: str) -> float | None:
            value = row.get(name)
            return None if value in (None, "") else float(value)
        parsed.append(
            MonthlyHydrologyRecord(
                month=month,
                gatun_mean_ft=float(row["gatun_mean_ft"]),
                precipitation_mm=float(row["precipitation_mm"]),
                evaporation_mm=float(row["evaporation_mm"]),
                oceangoing_transits_daily_average=optional("oceangoing_transits_daily_average"),
                booking_slots_per_day=optional("booking_slots_per_day"),
                neopanamax_max_draft_ft=optional("neopanamax_max_draft_ft"),
                panamax_max_draft_ft=optional("panamax_max_draft_ft"),
                oni_lag_6w=optional("oni_lag_6w"),
            )
        )
    parsed.sort(key=lambda item: item.month)
    if len({item.month for item in parsed}) != len(parsed):
        raise ACPModelError("history CSV contains duplicate months")
    return parsed


def load_acp_daily_gatun_history(path: Path) -> list[DailyGatunLevel]:
    """Read ACP's official daily Gatun CSV from a local, authorized path.

    The function deliberately does not download or cache the file. ACP's own
    current page restricts copying and derivative publication; callers retain
    the raw CSV outside the repository and decide their permission scope.
    """

    with path.open(encoding="utf-8-sig", newline="") as handle:
        rows = list(csv.DictReader(handle))
    if not rows or not {"DATE_LOG", "GATUN_LAKE_LEVEL(FEET)"}.issubset(rows[0]):
        raise ACPModelError("ACP daily history needs DATE_LOG and GATUN_LAKE_LEVEL(FEET) columns")
    parsed: list[DailyGatunLevel] = []
    for row in rows:
        try:
            stamp = datetime.strptime(str(row["DATE_LOG"]), "%Y-%m-%d").date().isoformat()
            level = float(str(row["GATUN_LAKE_LEVEL(FEET)"]).strip())
        except (TypeError, ValueError) as exc:
            raise ACPModelError(f"invalid ACP daily Gatun row: {row}") from exc
        parsed.append(DailyGatunLevel(stamp, level))
    if len({row.observation_date for row in parsed}) != len(parsed):
        raise ACPModelError("ACP daily history contains duplicate dates")
    return sorted(parsed, key=lambda item: item.observation_date)


def load_nasa_power_daily_meteorology(path: Path) -> list[DailyMeteorology]:
    """Read a local NASA POWER point response without calling the network.

    `PRECTOTCORR` is precipitation and `EVLAND` is land evaporation.  The
    latter is *not* the reservoir evaporation calculation in Muñoz et al.; it
    is a free, reproducible sensitivity proxy pending a paper-compatible
    ERA5-Land reservoir-evaporation preparation.
    """

    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
        parameters = payload["properties"]["parameter"]
        precipitation = parameters["PRECTOTCORR"]
        evaporation = parameters["EVLAND"]
    except (OSError, KeyError, TypeError, json.JSONDecodeError) as exc:
        raise ACPModelError("NASA POWER JSON needs properties.parameter.PRECTOTCORR and EVLAND") from exc
    if set(precipitation) != set(evaporation):
        raise ACPModelError("NASA POWER precipitation and evaporation dates do not align")
    parsed = []
    for stamp, rain in precipitation.items():
        try:
            observed = datetime.strptime(str(stamp), "%Y%m%d").date().isoformat()
            rain_value = float(rain)
            evap_value = float(evaporation[stamp])
        except (TypeError, ValueError) as exc:
            raise ACPModelError(f"invalid NASA POWER daily row: {stamp}") from exc
        if rain_value <= -900 or evap_value <= -900:
            continue
        parsed.append(DailyMeteorology(observed, rain_value, evap_value))
    if not parsed:
        raise ACPModelError("NASA POWER payload contains no valid meteorology rows")
    return sorted(parsed, key=lambda item: item.observation_date)


def aggregate_daily_hydrology_proxy(
    levels: list[DailyGatunLevel], meteorology: list[DailyMeteorology]
) -> list[MonthlyHydrologyRecord]:
    """Build a local monthly history from ACP levels and NASA POWER proxy data.

    A full calendar month needs at least 20 daily level readings and 20 daily
    meteorology readings. The common period only is used, and no missing day or
    month is imputed. This is suitable for a reproducible sensitivity/backtest,
    not for labelling the resulting model as identical to the paper's observed
    precipitation plus calculated reservoir evaporation specification.
    """

    levels_by_month: dict[str, list[float]] = {}
    weather_by_month: dict[str, list[DailyMeteorology]] = {}
    for item in levels:
        levels_by_month.setdefault(item.observation_date[:7], []).append(item.water_level_ft)
    for item in meteorology:
        weather_by_month.setdefault(item.observation_date[:7], []).append(item)
    records = []
    for month in sorted(set(levels_by_month) & set(weather_by_month)):
        observed_levels = levels_by_month[month]
        observed_weather = weather_by_month[month]
        if len(observed_levels) < 20 or len(observed_weather) < 20:
            continue
        records.append(MonthlyHydrologyRecord(
            month=month,
            gatun_mean_ft=statistics.fmean(observed_levels),
            precipitation_mm=sum(item.precipitation_mm for item in observed_weather),
            evaporation_mm=sum(item.evaporation_proxy_mm for item in observed_weather),
        ))
    if not records:
        raise ACPModelError("no complete common month in ACP/NASA daily inputs")
    return records


def parse_noaa_oni_text(text: str) -> dict[str, float]:
    """Parse NOAA CPC's ONI table into values keyed by centre month."""

    season_to_month = {
        "DJF": 1, "JFM": 2, "FMA": 3, "MAM": 4, "AMJ": 5, "MJJ": 6,
        "JJA": 7, "JAS": 8, "ASO": 9, "SON": 10, "OND": 11, "NDJ": 12,
    }
    parsed: dict[str, float] = {}
    for line in text.splitlines():
        match = re.match(r"\s*([A-Z]{3})\s+(\d{4})\s+[-0-9.]+\s+([-0-9.]+)\s*$", line)
        if not match or match.group(1) not in season_to_month:
            continue
        parsed[f"{int(match.group(2)):04d}-{season_to_month[match.group(1)]:02d}"] = float(match.group(3))
    if not parsed:
        raise ACPModelError("NOAA ONI table contains no season rows")
    return parsed


def attach_lagged_oni(
    records: list[MonthlyHydrologyRecord], oni_by_month: dict[str, float], *, lag_months: int = 2
) -> list[MonthlyHydrologyRecord]:
    """Attach only ONI values that would have been observable before the target month."""

    enriched = []
    for row in records:
        stamp = datetime.strptime(row.month, "%Y-%m")
        serial = stamp.year * 12 + stamp.month - 1 - lag_months
        lagged_month = f"{serial // 12:04d}-{serial % 12 + 1:02d}"
        enriched.append(replace(row, oni_lag_6w=oni_by_month.get(lagged_month)))
    return enriched


