"""Research-grade, local-only Panama Canal hydrology and operations model.

The model deliberately separates three layers:

1. Hydrology: monthly Gatun level from precipitation and evaporation using the
   covariates and extreme-level weighting in Muñoz et al. (2025), *Drying of
   the Panama Canal in a Warming Climate*, Geophysical Research Letters,
   doi:10.1029/2025GL117038.
2. Operations: ACP-issued booking-slot and maximum-draft notices.  These are
   observed management decisions and override any statistical inference.
3. Traffic: official monthly ocean-going transit counts (when supplied) are
   modelled only after a chronological backtest beats a seasonal baseline.

Gatun level is never converted directly into DWT, ship counts, or a closure
percentage.  That relationship is mediated by ACP operations and is not a
physical constant.
"""

