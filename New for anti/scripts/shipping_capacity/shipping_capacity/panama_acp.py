def fetch_public_pdf(url: str, *, timeout_seconds: int = 45) -> bytes:
    """Download a public ACP document without persisting it in the repository."""

    parts = urlsplit(url)
    encoded_url = urlunsplit((parts.scheme, parts.netloc, quote(parts.path, safe="/%:@"), parts.query, parts.fragment))
    request = urllib.request.Request(
        encoded_url,
        headers={"User-Agent": "GlobalTradeDashboardResearch/1.0 (+noncommercial)"},
    )
    with urllib.request.urlopen(request, timeout=timeout_seconds) as response:
        payload = response.read()
    if not payload.startswith(b"%PDF"):
        raise ACPModelError("ACP source did not return a PDF document")
    return payload


def fetch_public_text(url: str, *, timeout_seconds: int = 45) -> str:
    """Fetch a public text/CSV response in memory without a raw cache."""

    parts = urlsplit(url)
    encoded_url = urlunsplit((parts.scheme, parts.netloc, quote(parts.path, safe="/%:@"), parts.query, parts.fragment))
    request = urllib.request.Request(
        encoded_url,
        headers={"User-Agent": "GlobalTradeDashboardResearch/1.0 (+noncommercial)"},
    )
    with urllib.request.urlopen(request, timeout=timeout_seconds) as response:
        return response.read().decode("utf-8-sig")


def _earthdata_token() -> str:
    """Get an Earthdata token from the process environment, never a source file."""

    token = os.environ.get("NASA_EARTHDATA") or os.environ.get("EARTHDATA_TOKEN")
    if not token:
        raise ACPModelError("NASA_EARTHDATA or EARTHDATA_TOKEN is required for GPM IMERG collection")
    return token


def _earthdata_request(url: str, token: str) -> urllib.request.Request:
    return urllib.request.Request(
        url,
        headers={
            "Authorization": f"Bearer {token}",
            "User-Agent": "GlobalTradeDashboardResearch/1.0 (+noncommercial)",
        },
    )


def _gpm_granules(start_date: str, end_date: str, token: str) -> list[tuple[str, str]]:
    """Resolve daily GPM IMERG files through CMR without storing an index cache."""

    try:
        start = datetime.strptime(start_date, "%Y-%m-%d").date()
        end = datetime.strptime(end_date, "%Y-%m-%d").date()
    except ValueError as exc:
        raise ACPModelError("GPM date range must use YYYY-MM-DD") from exc
    if end < start:
        raise ACPModelError("GPM end date precedes start date")
    if (end - start).days + 1 > 31:
        raise ACPModelError("GPM collection is capped at 31 days per local run to avoid bulk raw-data caching")
    query = urllib.parse.urlencode({
        "short_name": GPM_IMERG_DAILY_SHORT_NAME,
        "version": GPM_IMERG_DAILY_VERSION,
        "temporal": f"{start.isoformat()}T00:00:00Z,{end.isoformat()}T23:59:59Z",
        "page_size": "2000",
    })
    request = _earthdata_request(f"https://cmr.earthdata.nasa.gov/search/granules.json?{query}", token)
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            entries = json.loads(response.read().decode("utf-8"))["feed"]["entry"]
    except (KeyError, OSError, json.JSONDecodeError) as exc:
        raise ACPModelError("Earthdata CMR did not return GPM IMERG granules") from exc
    resolved = []
    for entry in entries:
        stamp = str(entry.get("time_start", ""))[:10]
        source_url = next(
            (str(link["href"]) for link in entry.get("links", []) if str(link.get("href", "")).endswith(".nc4")),
            None,
        )
        if source_url and re.fullmatch(r"\d{4}-\d{2}-\d{2}", stamp):
            resolved.append((stamp, source_url))
    if not resolved:
        raise ACPModelError("no downloadable GPM IMERG daily granules found for requested dates")
    if len({stamp for stamp, _ in resolved}) != len(resolved):
        raise ACPModelError("GPM IMERG query returned duplicate daily granules")
    return sorted(resolved)


def _gpm_window_precipitation_mm(path: Path, bbox: tuple[float, float, float, float]) -> float:
    """Read a GPM daily NetCDF4 file and return latitude-weighted monitor-window rain.

    GPM's daily `precipitation` unit is mm/day, so its numerical daily mean is
    also the daily accumulated depth.  The coordinate-order check prevents a
    silent lon/lat transpose when a collection version changes.
    """

    try:
        import h5py
        import numpy as np
    except ImportError as exc:  # pragma: no cover - runtime dependency
        raise ACPModelError("h5py and numpy are required to read GPM IMERG NetCDF4") from exc
    south, west, north, east = bbox
    if not (south < north and west < east):
        raise ACPModelError("GPM monitoring bbox must be south, west, north, east")
    with h5py.File(path, "r") as handle:
        if not {"lat", "lon", "precipitation"}.issubset(handle):
            raise ACPModelError("GPM IMERG file lacks lat, lon or precipitation")
        lat = np.asarray(handle["lat"][:], dtype=float)
        lon = np.asarray(handle["lon"][:], dtype=float)
        precipitation = np.asarray(handle["precipitation"][:], dtype=float)
    if precipitation.ndim != 3 or precipitation.shape[0] != 1:
        raise ACPModelError("GPM daily precipitation must have a single time dimension")
    lat_mask = (lat >= south) & (lat <= north)
    lon_mask = (lon >= west) & (lon <= east)
    if not lat_mask.any() or not lon_mask.any():
        raise ACPModelError("GPM monitoring bbox contains no grid cells")
    values = precipitation[0]
    if values.shape == (len(lon), len(lat)):
        window = values[lon_mask, :][:, lat_mask]
        latitude_weights = np.cos(np.deg2rad(lat[lat_mask]))
        weights = np.broadcast_to(latitude_weights, window.shape)
    elif values.shape == (len(lat), len(lon)):
        window = values[lat_mask, :][:, lon_mask]
        latitude_weights = np.cos(np.deg2rad(lat[lat_mask]))
        weights = np.broadcast_to(latitude_weights[:, None], window.shape)
    else:
        raise ACPModelError("GPM precipitation dimensions do not match latitude/longitude coordinates")
    valid = np.isfinite(window) & (window >= 0)
    if not valid.any():
        raise ACPModelError("GPM monitor window has no valid precipitation cells")
    return float(np.average(window[valid], weights=weights[valid]))


def fetch_gpm_imerg_daily_monitor(
    start_date: str,
    end_date: str,
    *,
    bbox: tuple[float, float, float, float] = GATUN_MONITORING_BBOX,
) -> list[DailySatellitePrecipitation]:
    """Collect short recent GPM observations into memory/temporary files only.

    Each source file is removed at the end of this call.  Derived daily means
    remain eligible for a local research report, with product and URL lineage.
    """

    token = _earthdata_token()
    resolved = _gpm_granules(start_date, end_date, token)
    with tempfile.TemporaryDirectory(prefix="gpm-imerg-") as directory:
        temporary_dir = Path(directory)

        def download(stamp: str, source_url: str) -> tuple[str, str, Path]:
            temporary_path = temporary_dir / f"{stamp}.nc4"
            try:
                with urllib.request.urlopen(_earthdata_request(source_url, token), timeout=180) as response:
                    temporary_path.write_bytes(response.read())
            except OSError as exc:
                raise ACPModelError(f"could not download GPM IMERG file for {stamp}") from exc
            return stamp, source_url, temporary_path

        # The daily files are roughly 30 MB each.  The GES DISC endpoint can
        # reject overlapping authenticated transfers, so this stays serial and
        # bounded to a short window rather than retrying or bulk-downloading.
        with ThreadPoolExecutor(max_workers=1) as executor:
            futures = [executor.submit(download, stamp, source_url) for stamp, source_url in resolved]
            downloaded = [future.result() for future in futures]
        # h5py's binary backend is not safely assumed to be thread-safe.  Only
        # the network transfer is concurrent; HDF5 decoding is deterministic.
        rows = [
            DailySatellitePrecipitation(
                observation_date=stamp,
                precipitation_mm=round(_gpm_window_precipitation_mm(path, bbox), 4),
                product_id=f"{GPM_IMERG_DAILY_SHORT_NAME}.{GPM_IMERG_DAILY_VERSION}",
                source_url=source_url,
            )
            for stamp, source_url, path in downloaded
        ]
    return sorted(rows, key=lambda row: row.observation_date)


def summarize_gpm_imerg_monitor(rows: list[DailySatellitePrecipitation]) -> dict[str, Any]:
    """Summarize observed GPM rainfall without rebranding it as a hydrology forecast."""

    if not rows:
        return {"status": "not_supplied"}
    ordered = sorted(rows, key=lambda row: row.observation_date)
    if len({row.observation_date for row in ordered}) != len(ordered):
        raise ACPModelError("GPM monitor contains duplicate observation dates")
    values = [row.precipitation_mm for row in ordered]
    return {
        "status": "observed_satellite_precipitation_local_only",
        "product_id": ordered[0].product_id,
        "monitoring_geometry": {
            "type": "rectangular_proxy_not_official_watershed_boundary",
            "bbox_south_west_north_east": list(GATUN_MONITORING_BBOX),
        },
        "observation_range": [ordered[0].observation_date, ordered[-1].observation_date],
        "observed_day_count": len(ordered),
        "total_precipitation_mm": round(sum(values), 3),
        "mean_precipitation_mm_per_day": round(statistics.fmean(values), 3),
        "daily_rows_local_only": [asdict(row) for row in ordered],
        "interpretation": (
            "recent GPM IMERG satellite observation for the declared rectangular monitoring window; "
            "not an official Gatun watershed total, not a water-level forecast, and not directly mixed "
            "into the NASA POWER-calibrated historical hydrology model without bias calibration"
        ),
    }


def compare_gpm_imerg_year_over_year(
    current_rows: list[DailySatellitePrecipitation], previous_year_rows: list[DailySatellitePrecipitation]
) -> dict[str, Any]:
    """Compare identical calendar days in GPM observations one year apart.

    The comparison is withheld rather than silently shortening either period;
    this matters when the latest GPM Late Run day is still delayed.
    """

    if not current_rows or not previous_year_rows:
        return {"status": "comparison_not_supplied"}
    current = sorted(current_rows, key=lambda row: row.observation_date)
    previous_by_date = {row.observation_date: row for row in previous_year_rows}
    expected_previous_dates = []
    for row in current:
        observed = date.fromisoformat(row.observation_date)
        try:
            expected_previous_dates.append(observed.replace(year=observed.year - 1).isoformat())
        except ValueError:
            return {"status": "withheld_leap_day_not_comparable"}
    if len(set(expected_previous_dates)) != len(expected_previous_dates):
        return {"status": "withheld_duplicate_comparison_dates"}
    if any(stamp not in previous_by_date for stamp in expected_previous_dates):
        return {
            "status": "withheld_missing_matching_previous_year_observation",
            "required_previous_dates": expected_previous_dates,
        }
    current_total = sum(row.precipitation_mm for row in current)
    previous_total = sum(previous_by_date[stamp].precipitation_mm for stamp in expected_previous_dates)
    difference = current_total - previous_total
    return {
        "status": "comparable_observed_same_calendar_days",
        "current_observation_range": [current[0].observation_date, current[-1].observation_date],
        "previous_year_observation_range": [expected_previous_dates[0], expected_previous_dates[-1]],
        "observed_day_count": len(current),
        "current_total_precipitation_mm": round(current_total, 3),
        "previous_year_total_precipitation_mm": round(previous_total, 3),
        "difference_mm": round(difference, 3),
        "change_pct": None if previous_total == 0 else round(100 * difference / previous_total, 2),
        "interpretation": (
            "same-calendar-day satellite precipitation comparison only; it is not a year-over-year "
            "change in canal traffic, lake storage, or a forecast"
        ),
    }


